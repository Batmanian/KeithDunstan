const { DateTime } = require("luxon");
const { execFileSync } = require("child_process");
const navigationPlugin = require('@11ty/eleventy-navigation')
const { dateToRfc822 } = require('@11ty/eleventy-plugin-rss')
const metagenPlugin = require('eleventy-plugin-metagen')
const matter = require("gray-matter");
const books = require("./src/_data/books.json");

module.exports = function(eleventyConfig) {

  // Repository guidance files can live beside image assets, but they are not
  // site content and may contain Liquid examples that Eleventy cannot render.
  eleventyConfig.ignores.add("src/assets/images/*.md");

  // Powers the {% metagen %} shortcode used in snippets/opengraph.njk to
  // generate Open Graph / Twitter Card / canonical tags for every page.
  eleventyConfig.addPlugin(metagenPlugin);

  // Provides the dateToRfc822 filter used by src/feed.njk (/feed.xml).
  eleventyConfig.addFilter("dateToRfc822", dateToRfc822);

  eleventyConfig.setDataDeepMerge(true);

  const EXCLUDED_TAGS = ["all", "nav", "post", "posts", "book", "books", "article", "articles"];

  // De-duplicates as well as excludes — Eleventy's data cascade has been seen
  // to double up a post's own tags array for at least one file, and a plain
  // authoring slip (the same tag listed twice) shouldn't show twice either.
  function filterTagList(tags) {
    return [...new Set(tags || [])].filter(tag => !EXCLUDED_TAGS.includes(tag));
  }

  eleventyConfig.addFilter("filterTagList", filterTagList)

  // _redirects and _headers live at the repo root; Netlify only reads them
  // from the publish directory, so they have to be passed through into the
  // build output.
  eleventyConfig.addPassthroughCopy("_redirects");
  eleventyConfig.addPassthroughCopy("_headers");

  // CNAME (repo root) tells GitHub Pages which custom domain to serve.
  // npm run build's clean-prod step (`rm -rf docs/*`) wipes it on every
  // build, and nothing used to recreate it — hence the repo's long history
  // of "Create CNAME" / "Delete CNAME" commits from re-adding it by hand
  // after the fact. Passing it through here means it's back on every build.
  eleventyConfig.addPassthroughCopy("CNAME");

  // Copy the static robots.txt to the site root
  eleventyConfig.addPassthroughCopy({ "src/robots.txt": "robots.txt" });

  // Lets src/_data/topics.md (generated by scripts/generate-topics.js) be read
  // as global data — only its YAML frontmatter is used.
  eleventyConfig.addDataExtension("md", contents => matter(contents).data);

  eleventyConfig.addFilter("findTopic", (topicList, name) => {
    return (topicList || []).find(topic => topic.name === name);
  });

  // Auto-populates as new files are added to src/articles/bulletin/ — no
  // per-article tag or manual link list to keep in sync.
  eleventyConfig.addCollection("bulletin", collection => {
    return collection.getFilteredByGlob("src/articles/bulletin/*.md")
      .sort((a, b) => a.date - b.date);
  });

  // Same auto-populating pattern as the bulletin collection above, for
  // src/articles/walkabout-magazine/.
  eleventyConfig.addCollection("walkabout", collection => {
    return collection.getFilteredByGlob("src/articles/walkabout-magazine/*.md")
      .sort((a, b) => a.date - b.date);
  });

  // Same auto-populating pattern as the bulletin collection above, for
  // src/articles/the-age/.
  eleventyConfig.addCollection("theage", collection => {
    return collection.getFilteredByGlob("src/articles/the-age/*.md")
      .sort((a, b) => a.date - b.date);
  });

  // Same auto-populating pattern as the bulletin collection above, for
  // src/articles/readers-digest/.
  eleventyConfig.addCollection("readersdigest", collection => {
    return collection.getFilteredByGlob("src/articles/readers-digest/*.md")
      .sort((a, b) => a.date - b.date);
  });

  // Merges every transcribed article with the full book bibliography
  // (src/_data/books.json) into one date-sorted list for src/timeline.njk.
  // Books only carry a publication year, so they're pinned to 1 January of
  // that year for sorting; the template shows year-only precision for them.
  // Every item also gets a `publication` label — an article's own
  // `categories[0]` when set, otherwise its folder name humanized (covers
  // src/articles/the-australian-gourmet/, which carries no categories
  // frontmatter) — used to colour-code and sort the timeline by masthead.
  eleventyConfig.addCollection("timeline", collection => {
    const articleItems = collection.getFilteredByTag("article").map(item => {
      const folderSlug = item.url.split("/")[2];
      const publication = (item.data.categories && item.data.categories.length)
        ? item.data.categories[0]
        : humanizeSlug(folderSlug);
      return {
        date: item.date,
        title: item.data.title,
        url: item.url,
        summary: item.data.summary,
        publication,
        tags: item.data.tags,
        isBook: false
      };
    });
    const bookItems = books.map(book => ({
      date: new Date(Date.UTC(book.year, 0, 1)),
      title: book.title,
      url: book.url,
      summary: book.summary,
      publication: "Book",
      tags: null,
      isBook: true,
      external: !!book.external
    }));
    return [...articleItems, ...bookItems].sort((a, b) => a.date - b.date);
  });

  // The N most-referenced tags across a set of collection items (e.g.
  // collections.bulletin), for the "Top topics" line on snippets/bulletin.njk
  // and snippets/walkabout.njk. Same counting logic as the tagList collection
  // above, scoped to a subset of items rather than the whole site.
  eleventyConfig.addFilter("topTopics", (items, limit) => {
    const counts = {};
    (items || []).forEach(item => {
      filterTagList(item.data && item.data.tags).forEach(tag => {
        counts[tag] = (counts[tag] || 0) + 1;
      });
    });
    return Object.keys(counts)
      .map(tagName => ({ tagName, tagCount: counts[tagName] }))
      .sort((a, b) => b.tagCount - a.tagCount || a.tagName.localeCompare(b.tagName))
      .slice(0, limit || 10);
  });

  // Groups a sorted collection of articles into { decade, articles } buckets,
  // ordered oldest decade first, for rendering as an accordion.
  eleventyConfig.addFilter("groupByDecade", articles => {
    const groups = {};
    (articles || []).forEach(article => {
      const decade = Math.floor(article.date.getFullYear() / 10) * 10;
      if (!groups[decade]) groups[decade] = [];
      groups[decade].push(article);
    });
    return Object.keys(groups)
      .sort((a, b) => a - b)
      .map(decade => ({ decade: Number(decade), articles: groups[decade] }));
  });

  // Groups a sorted collection into individual years, oldest first.
  eleventyConfig.addFilter("groupByYear", articles => {
    const groups = {};
    (articles || []).forEach(article => {
      const year = article.date.getFullYear();
      if (!groups[year]) groups[year] = [];
      groups[year].push(article);
    });
    return Object.keys(groups)
      .sort((a, b) => a - b)
      .map(year => ({ year: Number(year), articles: groups[year] }));
  });

  eleventyConfig.addCollection("tagList", collection => {
    const tagsObject = {}
    collection.getAll().forEach(item => {
      if (!item.data.tags) return;
      [...new Set(item.data.tags)]
        .filter(tag => !['post', 'all', 'book', 'books', 'article', 'articles'].includes(tag))
        .forEach(tag => {
          if(typeof tagsObject[tag] === 'undefined') {
            tagsObject[tag] = 1
          } else {
            tagsObject[tag] += 1
          }
        });
    });

    const tagList = []
    Object.keys(tagsObject).forEach(tag => {
      tagList.push({ tagName: tag, tagCount: tagsObject[tag] })
    })
    return tagList.sort((a, b) => b.tagCount - a.tagCount)

  });


  // Add a filter using the Config API
  eleventyConfig.addWatchTarget("./src/scss/");
  eleventyConfig.setBrowserSyncConfig({
    reloadDelay: 400
  });

  eleventyConfig.addFilter("readableDate", dateObj => {
    return DateTime.fromJSDate(dateObj, {
      zone: 'utc'
    }).toFormat("dd LLL yyyy");
  });

  // Books show only the year (chapter-level day precision isn't meaningful
  // for a book's publication date); articles keep the full day date.
  eleventyConfig.addFilter("postDate", (dateObj, tags) => {
    const dt = DateTime.fromJSDate(dateObj, { zone: 'utc' });
    return (tags || []).includes("book") ? dt.toFormat("yyyy") : dt.toFormat("dd LLL yyyy");
  });

  // https://html.spec.whatwg.org/multipage/common-microsyntaxes.html#valid-date-string
  eleventyConfig.addFilter('htmlDateString', (dateObj) => {
    return DateTime.fromJSDate(dateObj, {
      zone: 'utc'
    }).toFormat('yyyy-LL-dd');
  });

  // Last commit date that touched a given source file, for the "Last
  // updated" line on articles and book chapters (snippets/postcontent.njk).
  // Computed straight from git history at build time rather than a
  // frontmatter field, so it can never go stale or need re-running after an
  // edit. Files not yet committed (e.g. brand new content) have no git log
  // yet, so this returns null and the template hides the line until the
  // next commit.
  const gitLastUpdatedCache = new Map();
  eleventyConfig.addFilter("gitLastUpdated", (inputPath) => {
    if (!inputPath) return null;
    if (gitLastUpdatedCache.has(inputPath)) return gitLastUpdatedCache.get(inputPath);
    let result = null;
    try {
      const out = execFileSync(
        "git",
        ["log", "-1", "--format=%ad", "--date=short", "--", inputPath],
        { cwd: __dirname, encoding: "utf8", timeout: 3000 }
      ).trim();
      if (out) result = new Date(`${out}T00:00:00Z`);
    } catch (e) {
      result = null;
    }
    gitLastUpdatedCache.set(inputPath, result);
    return result;
  });

  // Date a source file first appeared in git — used to order the RSS feed
  // (src/feed.njk) by when a page actually went up on the site, since the
  // `date` frontmatter is usually the item's decades-old historical
  // publication date and isn't useful for "what's new" ordering.
  const gitDateAddedCache = new Map();
  function getGitDateAdded(inputPath) {
    if (gitDateAddedCache.has(inputPath)) return gitDateAddedCache.get(inputPath);
    let result = null;
    try {
      const out = execFileSync(
        "git",
        ["log", "--diff-filter=A", "--format=%ad", "--date=short", "--follow", "--", inputPath],
        { cwd: __dirname, encoding: "utf8", timeout: 3000 }
      ).trim().split("\n").filter(Boolean);
      const firstAdd = out[out.length - 1];
      if (firstAdd) result = new Date(`${firstAdd}T00:00:00Z`);
    } catch (e) {
      result = null;
    }
    gitDateAddedCache.set(inputPath, result);
    return result;
  }

  // Newest-added-first feed of book chapters + articles, for /feed.xml.
  eleventyConfig.addCollection("recentContent", collection => {
    return collection.getAll()
      .filter(item => (item.data.tags || []).includes("book") || (item.data.tags || []).includes("article"))
      .map(item => ({
        title: item.data.title,
        summary: item.data.summary,
        url: item.url,
        dateAdded: getGitDateAdded(item.inputPath) || item.date
      }))
      .sort((a, b) => b.dateAdded - a.dateAdded)
      .slice(0, 30);
  });

  // Nunjucks has no built-in string split — used to pull the collection
  // slug out of a page's URL (e.g. "/books/ratbags/..." -> "ratbags").
  eleventyConfig.addFilter("split", (str, delimiter) => (str || "").split(delimiter));

  // Turns a URL slug into a display label — used to derive a "publication"
  // name (e.g. book title) for pages that have no explicit `categories`
  // frontmatter, for the search results metadata, and for the timeline
  // collection below.
  function humanizeSlug(slug) {
    return (slug || "")
      .split("-")
      .map(word => word.charAt(0).toUpperCase() + word.slice(1))
      .join(" ");
  }
  eleventyConfig.addFilter("humanizeSlug", humanizeSlug);

  return {
    dir: {
      input: "src",
      output: "dev"
    }
  };

};
